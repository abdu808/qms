-- ─────────────────────────────────────────────────────────────────────
-- Data Migration — قرار المشرف:
-- ─────────────────────────────────────────────────────────────────────
-- إلغاء التحويل التلقائي إلى ABORTED. الإغلاق النهائي يجب أن يكون قراراً
-- إنسانياً صادراً من مدير الجودة مع سبب موثَّق فقط.
--
-- هذه الترحيلة تُعيد جميع سجلات ABORTED التي أُنشئت تلقائياً (بدون قرار
-- يدوي صريح) إلى ESCALATED مستوى 2. السجلات المُغلقة يدوياً تحتفظ بحالتها
-- وتُمَيَّز بنمط النص "إغلاق نهائي" في qmNotes (الذي يكتبه /abort endpoint).
--
-- الفائدة:
--   • صدق السجل: لا تختفي المتأخرات صامتاً
--   • سيطرة QM: يقرر متى يُغلق ولماذا
--   • سجل قابل للتدقيق: كل إغلاق له سبب مكتوب
-- ─────────────────────────────────────────────────────────────────────

UPDATE "KpiFollowUp"
SET
    status = 'ESCALATED',
    "escalationLevel" = 2,
    "updatedAt" = CURRENT_TIMESTAMP
WHERE
    status = 'ABORTED'
    AND ("qmNotes" IS NULL OR "qmNotes" NOT LIKE '%إغلاق نهائي%');
