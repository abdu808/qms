// مساعد idempotent
// ─────────────────────────────────────────────────────────────────────────────
async function upsert(label, items, existsFn, createFn) {
  let created = 0, skipped = 0;
  for (const item of items) {
    if (await existsFn(item)) { skipped++; continue; }
    await createFn(item);
    created++;
  }
  console.log(`[seed-iso] ${label}: أُنشئ ${created} | موجود ${skipped}`);
  return created;
}

